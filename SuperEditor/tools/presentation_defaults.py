"""Compile independent source presentation defaults; never changes the SES64 ABI."""
from pathlib import Path
import argparse
import hashlib
import json

ROOT=Path(__file__).resolve().parents[1]
PRESETS={'plain':0,'markdown':1,'full':3}


def validate_editor(value):
    if type(value) is not dict or set(value)!={'source_preset'}:
        raise ValueError('editor requires exactly source_preset')
    preset=value['source_preset']
    if type(preset) is not str or preset not in PRESETS:
        raise ValueError('editor.source_preset must be plain, markdown or full')
    return PRESETS[preset]


def compile_defaults(data,catalog=None):
    # Validate the same COMPLETE host input used for the font defaults, before
    # emitting anything. Legacy input without [editor] defaults to Full.
    import editor_settings
    editor_settings.read_toml(data,catalog)
    mapping=editor_settings.tomllib.loads(bytes(data).decode('utf-8'))
    caps=validate_editor(mapping.get('editor',{'source_preset':'full'}))
    name=next(k for k,v in PRESETS.items() if v==caps)
    include=('; GENERATED by tools/presentation_defaults.py; independent of SES64.\n'
             '.ifndef SE_PRESENTATION_DEFAULT\n'
             'SE_PRESENTATION_DEFAULT=%d\n.endif\n'%caps).encode('ascii')
    manifest=dict(schema=1,source_preset=name,capabilities=caps,
        structure=bool(caps&1),code_coloring=bool(caps&2),
        input_sha256=hashlib.sha256(bytes(data)).hexdigest(),
        storage='Separate one-byte session capability; SES64 font settings unchanged.',
        persistence='Host build default only; runtime changes/reset do not write configuration.')
    return {'presentation-defaults.inc':include,
            'presentation-defaults.json':(json.dumps(manifest,sort_keys=True,indent=2)+'\n').encode()}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('config',nargs='?',type=Path,default=ROOT/'config/editor-defaults.toml')
    parser.add_argument('--out-dir',type=Path,default=ROOT/'build/editor-settings')
    args=parser.parse_args()
    import editor_settings
    try:
        outputs=compile_defaults(args.config.read_bytes())
        editor_settings.write_outputs(outputs,args.out_dir)
    except (editor_settings.SettingsError,ValueError,OSError) as exc:
        parser.exit(2,str(exc)+'\n')
    print(json.dumps(dict(status='generated',files=list(outputs))))


if __name__=='__main__':main()
