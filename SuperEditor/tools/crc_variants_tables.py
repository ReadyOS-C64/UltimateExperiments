"""Generate native ca65 constant tables; verifier uses independent binascii."""
from pathlib import Path
import sys

def table_entry(value):
 crc=value<<8
 for _ in range(8):crc=((crc<<1)^0x1021 if crc&0x8000 else crc<<1)&0xFFFF
 return crc

def emit(name,data):
 return name+':\n'+''.join('    .byte '+','.join(f'${x:02X}' for x in data[i:i+16])+'\n' for i in range(0,len(data),16))

def generate():
 table=[table_entry(i) for i in range(256)]
 text='; Generated by tools/crc_variants_tables.py. Do not edit.\n.segment "TABLE256"\ncrc256_tables_start:\n'
 text+=emit('crc256_lo',[x&255 for x in table])+emit('crc256_hi',[x>>8 for x in table])+'crc256_tables_end:\n'
 text+='\n.segment "TABLE64"\ncrc64_tables_start:\n'
 for name,values in [('low',[table[i] for i in range(16)]),('high',[table[i<<4] for i in range(16)])]:
  text+=emit('crc64_'+name+'_lo',[x&255 for x in values])+emit('crc64_'+name+'_hi',[x>>8 for x in values])
 text+='crc64_tables_end:\n\n.segment "TABLE_BAD"\n    .byte $A5\n'
 text+=emit('crc256_bad_lo',[x&255 for x in table])+emit('crc256_bad_hi',[x>>8 for x in table])
 return text
if __name__=='__main__':Path(sys.argv[1]).write_text(generate())
